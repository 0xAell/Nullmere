#!/usr/bin/env bash
# Makes every model of the world again, from its script in Art/blender, with
# Blender's own Python (the bpy module), and writes each into the package with
# Art/embed.py: one command for all of them (plan 5.1).
#
# Which models there are, and how each was made, is read from the files
# Art/embed.py wrote under Sources/NullmereModels/Art: each says on its first
# line which model it holds and the script, and the script's arguments, that
# made it ("made by Art/blender/keep.py seat"), and names the enum and the
# constant it fills.
#
#   python3.13 -m pip install bpy==5.2.4      # Blender's Python, once
#   PYTHON=python3.13 scripts/build-models.sh  # make them all, and embed them
#   scripts/build-models.sh --embed            # embed the models as they are
#   scripts/build-models.sh --only shrines     # make and embed one
#
# CI makes them all by hand or when a script changes (.github/workflows/
# models.yml) and keeps what it made on the models branch.
set -euo pipefail
cd "$(dirname "$0")/.."
python="${PYTHON:-python3}"
make=yes
only=""
while [ $# -gt 0 ]; do
    case "$1" in
        --embed) make=no ;;
        --only) only="$2"; shift ;;
        *) echo "usage: scripts/build-models.sh [--embed] [--only <model>]" >&2; exit 2 ;;
    esac
    shift
done

made=0
for swift in Sources/NullmereModels/Art/*.swift; do
    first="$(head -n 1 "$swift")"
    case "$first" in "// Generated by Art/embed.py from "*) ;; *) continue ;; esac
    # "// Generated by Art/embed.py from Art/models/keep.glb (made by Art/blender/keep.py seat)."
    rest="${first#// Generated by Art/embed.py from }"
    glb="${rest%% *}"
    maker="${rest#* (made by }"
    maker="${maker%).}"
    read -r script extra <<<"$maker"
    enum="$(grep -m 1 '^extension ' "$swift" | awk '{print $2}')"
    name="$(grep -m 1 '    static let ' "$swift" | awk '{print $3}')"
    model="$(basename "$glb" .glb)"
    if [ -n "$only" ] && [ "$only" != "$model" ]; then continue; fi
    if [ "$make" = yes ]; then
        echo "== $model: $script ${extra:-}"
        # shellcheck disable=SC2086
        "$python" "$script" "$glb" $extra
    fi
    python3 Art/embed.py "$glb" "$swift" "$enum" "$name" "$maker"
    made=$((made + 1))
done
if [ "$made" -eq 0 ]; then
    echo "No model made: none is named ${only:-in Sources/NullmereModels/Art}." >&2
    exit 1
fi
if [ "$make" = yes ]; then echo "$made models made and embedded."; else echo "$made models embedded."; fi
